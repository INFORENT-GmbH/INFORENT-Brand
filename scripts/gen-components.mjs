#!/usr/bin/env node
// Erzeugt aus components.def.mjs (die EINE Definition der Baustein-Optik):
//   components.css    Klassen: .ir-btn, .ir-input, .ir-badge, .ir-alert, .ir-card, .ir-panel, .ir-action-bar
//   components.js     dieselben Stile als Objekte (Portal: Inline-Styles in React)
//   components.d.ts   Typen mit den exakten Literalwerten, damit sie ohne Umweg als
//                     React.CSSProperties durchgehen
//
//   node scripts/gen-components.mjs           # schreiben
//   node scripts/gen-components.mjs --check   # Exit 1, wenn die Dateien nicht passen
//
// Präfix `ir-`, damit keine Klasse eines Verbrauchers getroffen wird. Jede Klasse
// ist EINE Klasse tief (Modifier kombinieren sich per Reihenfolge in der Datei):
// Rahmen-/Größen-/Varianten-Regeln kommen nach der Basis und gewinnen deshalb.

import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import * as def from '../components.def.mjs'

const root = new URL('..', import.meta.url)
const kebab = k => k.replace(/[A-Z]/g, c => `-${c.toLowerCase()}`)
const decls = o => Object.entries(o).map(([k, val]) => `  ${kebab(k)}: ${val};`).join('\n')
const rule = (sel, o) => `${sel} {\n${decls(o)}\n}`
const variantName = k => kebab(k)

const { button, input, badge, alert, card, panel, actionBar, controlHeight } = def

const badgeSkin = (t, variant) => {
  const c = badge.tones[t]
  if (variant === 'solid') return { background: c.solid, color: c.onSolid, border: '1px solid transparent' }
  if (variant === 'outline') return { background: 'transparent', color: c.text, border: `1px solid ${badge.outlineBorder}` }
  return { background: c.soft, color: c.text, border: '1px solid transparent' }
}
const alertSkin = t => { const c = alert.tones[t]; return { background: c.bg, color: c.fg, border: `1px solid ${c.border}` } }

const css = [
  '/* GENERATED by scripts/gen-components.mjs from components.def.mjs — do not edit.',
  ' * Needs tokens.css (the values) and base.css (hover, focus, disabled) loaded first.',
  ' * Usage: <button class="ir-btn ir-btn--md ir-btn--primary">, <input class="ir-input">,',
  ' * <span class="ir-badge ir-badge--md ir-badge--success">, <div class="ir-alert ir-alert--error">. */',
  '',
  rule(':root', { '--control-height': controlHeight }),
  '',
  '/* ── Knopf ── */',
  rule('.ir-btn', { ...button.base, ...button.sizes.md, ...button.variants.secondary }),
  ...Object.entries(button.sizes).map(([k, o]) => rule(`.ir-btn--${k}`, o)),
  ...Object.entries(button.variants).map(([k, o]) => rule(`.ir-btn--${variantName(k)}`, o)),
  '/* Auf der dunklen Aktionsleiste. Die Klasse setzt der Baustein, nicht ein\n   Nachfahren-Selektor — ein Dialog, den die Leiste öffnet, bleibt hell. */',
  ...Object.entries(button.onBar).map(([k, o]) => rule(`.ir-btn--on-bar.ir-btn--${variantName(k)}`, o)),
  '/* Ein Link im Knopf-Look bekommt dieselbe Rückmeldung wie <button> in base.css. */',
  'a.ir-btn:hover {\n  filter: brightness(0.94);\n}\na.ir-btn:active {\n  filter: brightness(0.88);\n}',
  '/* Läuft (Spinner vor der Beschriftung): gesperrt, aber nicht ausgegraut. */',
  '.ir-btn[aria-busy="true"]:disabled {\n  filter: none;\n  cursor: progress;\n}',
  '',
  '/* ── Feld ── */',
  rule('.ir-input', input.base),
  rule('.ir-input--sm', input.sm),
  rule('.ir-input--lg', input.lg),
  rule('.ir-textarea', input.textarea),
  rule('.ir-input--mono', input.mono),
  rule('.ir-input--admin', input.admin),
  rule('.ir-input[aria-invalid="true"]', input.invalid),
  rule('.ir-input[readonly]', input.readOnly),
  '',
  '/* ── Abzeichen ── */',
  rule('.ir-badge', { ...badge.base, ...badge.sizes.md, ...badgeSkin('neutral', 'soft') }),
  ...Object.entries(badge.sizes).map(([k, o]) => rule(`.ir-badge--${k}`, o)),
  ...Object.keys(badge.tones).map(t => rule(`.ir-badge--${t}`, badgeSkin(t, 'soft'))),
  ...Object.keys(badge.tones).flatMap(t => ['solid', 'outline'].map(vr => rule(`.ir-badge--${vr}.ir-badge--${t}`, badgeSkin(t, vr)))),
  '',
  '/* ── Hinweis ── */',
  rule('.ir-alert', { ...alert.base, ...alertSkin('error') }),
  ...Object.keys(alert.tones).map(t => rule(`.ir-alert--${t}`, alertSkin(t))),
  '',
  '/* ── Flächen ── */',
  rule('.ir-card', card.base),
  rule('.ir-card--admin', card.admin),
  rule('.ir-panel', panel.plain),
  ...['plain', 'muted', 'inset'].map(k => rule(`.ir-panel--${k}`, { borderWidth: '0', ...panel[k] })),
  rule('.ir-panel--pad', panel.pad),
  '',
  '/* ── Aktionsleiste (Auswahl) ── */',
  rule('.ir-action-bar', actionBar),
  '',
].join('\n')

const head = '// GENERATED by scripts/gen-components.mjs from components.def.mjs — do not edit.\n'
const exported = { controlHeight, button, input, badge, alert, card, panel, actionBar }
const js = head +
  '// Die Baustein-Optik als Stilobjekte (Inline-Styles). Dieselbe Definition wie components.css.\n' +
  Object.entries(exported).map(([k, val]) => `export const ${k} = ${JSON.stringify(val, null, 2)}\n`).join('\n')

// Typen: exakte Literale (readonly), rekursiv.
const typeOf = (val, ind = '') => {
  if (typeof val === 'string') return JSON.stringify(val).replace(/^"|"$/g, "'").replace(/^'(.*)'$/, (_, s) => `'${s.replace(/'/g, "\\'")}'`)
  const inner = Object.entries(val).map(([k, x]) => `${ind}  readonly ${/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k)}: ${typeOf(x, ind + '  ')}`).join('\n')
  return `{\n${inner}\n${ind}}`
}
const dts = head + Object.entries(exported).map(([k, val]) => `export declare const ${k}: ${typeOf(val)}\n`).join('\n')

if (/undefined/.test(css)) {
  console.error('✗ components.def.mjs verweist auf eine Variable, die tokens.css nicht hat:\n' + css.split('\n').filter(l => l.includes('undefined')).join('\n'))
  process.exit(1)
}

const files = { 'components.css': css, 'components.js': js, 'components.d.ts': dts }
if (process.argv.includes('--check')) {
  const stale = Object.entries(files).filter(([f, s]) => !existsSync(new URL(f, root)) || readFileSync(new URL(f, root), 'utf8') !== s)
  if (stale.length) { console.error(`✗ ${stale.map(([f]) => f).join(', ')} passt nicht zu components.def.mjs — npm run gen`); process.exit(1) }
  console.log(`components: ok (${(css.match(/^\.ir-[^{]+\{/gm) || []).length} Klassen)`)
} else {
  for (const [f, s] of Object.entries(files)) writeFileSync(new URL(f, root), s)
  console.log(`components: geschrieben (${(css.match(/^\.ir-[^{]+\{/gm) || []).length} Klassen)`)
}
